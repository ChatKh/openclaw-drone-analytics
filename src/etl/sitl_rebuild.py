"""
Rebuild the SITL database and results from the recorded flights, in one command.

  python -m src.etl.sitl_rebuild                # -> data/sitl.db, data/sitl/<flight>/, sitl/RESULTS.md

sitl/flights.json lists every flight with its mission id and phase map, so nothing has to be
remembered or typed per flight. The database is deleted and rebuilt every time, so running it
again gives the same database and the same results: a flight added, a detector changed, or an
old command run by mistake, the answer is to run this again.

Only flights with status 'flown' (completed missions) go into the database and the detectors.
The others (no lift-off, could not land) are summarised from their logs.
"""
import argparse
import json
import logging
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from src.analytics import ml_detector, rule_detector
from src.db.database import connect
from src.etl import sitl_tlog as E

log = logging.getLogger("sitl_rebuild")

SITL_DIR = Path("sitl")
MANIFEST = SITL_DIR / "flights.json"
STATUSES = ("flown", "no_liftoff", "could_not_land")


@dataclass
class FlightResult:
    entry: dict
    summary: dict
    rows: int
    cruise_s: int
    max_altitude_m: float
    battery_checks: int | None = None          # None: not loaded (not a completed mission)
    rule_alerts: Counter = field(default_factory=Counter)
    ml_alerts: Counter = field(default_factory=Counter)


def load_manifest(path: Path = MANIFEST) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))["flights"]


def rebuild(manifest: Path = MANIFEST, db: Path = Path("data/sitl.db"), out: Path = Path("data/sitl"),
            model_path: Path = ml_detector.MODEL_PATH, bundle: dict | None = None) -> list[FlightResult]:
    base = manifest.parent
    for suffix in ("", "-wal", "-shm"):
        Path(str(db) + suffix).unlink(missing_ok=True)
    db.parent.mkdir(parents=True, exist_ok=True)

    results = []
    for entry in load_manifest(manifest):
        tlog = base / entry["file"]
        messages = list(E.extract(tlog))
        rows = E.transform(messages, E.load_phases(base / entry["phases"]), entry["mission_id"],
                           entry["mission_id"].split("_")[1])
        if not rows:
            raise SystemExit(f"{tlog}: no rows ({'; '.join(E.diagnose(messages))})")
        flight_dir = out / Path(entry["file"]).stem
        E.write_dataset(rows, flight_dir, entry["mission_id"])
        summary = E.flight_summary(messages, rows)
        (flight_dir / "flight_summary.json").write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
        r = FlightResult(entry, summary, len(rows),
                         sum(row["flight_mode"] in E.CRUISE_PHASES for row in rows),
                         max(row["altitude_m"] for row in rows))
        if entry["status"] == "flown":
            totals = E.load(flight_dir, db)
            if totals.rejected:
                raise SystemExit(f"{tlog}: {totals.rejected} rows rejected, e.g. {totals.examples[:1]}")
            r.battery_checks = len(rule_detector.battery_check_points(rows, rule_detector.RuleConfig()))
        results.append(r)
        log.info("%-45s %-14s %5d rows", entry["file"], entry["status"], len(rows))

    conn = connect(str(db))
    try:
        by_mission = {r.entry["mission_id"]: r for r in results}
        for a in rule_detector.run(conn):
            by_mission[a.mission_id].rule_alerts[a.anomaly_type] += 1
        for a in ml_detector.run(conn, bundle or ml_detector.load_or_train(model_path)):
            by_mission[a.mission_id].ml_alerts[a.anomaly_type] += 1
    finally:
        conn.close()
    return results


def _alerts(c: Counter | None, loaded: bool) -> str:
    if not loaded:
        return "-"
    return str(sum(c.values())) + (" (" + ", ".join(f"{n} {k}" for k, n in sorted(c.items())) + ")" if c else "")


def results_markdown(results: list[FlightResult]) -> str:
    """The table in sitl/RESULTS.md. Every number comes from the logs; nothing is typed in."""
    lines = [
        "# SITL results",
        "",
        "Generated by `python -m src.etl.sitl_rebuild` from the logs listed in `sitl/flights.json`.",
        "Do not edit by hand: change the code or the flights and run it again.",
        "",
        "No flight has a planted fault, so every alert is a false alarm. Wind estimate: ArduPilot's own",
        f"(`WIND` message) from forward flight on; 'over {E.WIND_LIMIT_MPS:g} after' is when its",
        f"{E.WIND_AVERAGE_S} s mean first passed {E.WIND_LIMIT_MPS:g} m/s.",
        "",
        "| Flight | Wind set (m/s) | Start heading | Outcome | Armed (s) | Cruise (s) | Wind estimate median / max | "
        f"Over {E.WIND_LIMIT_MPS:g} after (s) | Landing (s) | Touchdown (m/s) | Max altitude (m) | Battery used (%) | "
        "Battery-rule checks | Rule alerts | ML alerts | ArduPilot warnings |",
        "|" + "---|" * 16,
    ]
    for r in results:
        e, s, w = r.entry, r.summary, r.summary.get("wind_estimate")
        loaded = r.battery_checks is not None
        over = None if not w else w[f"{E.WIND_AVERAGE_S}s_mean_over_limit_after_s"]
        lines.append("| " + " | ".join([
            f"`{Path(e['file']).name}`",
            f"{e['wind_mps']:g}",
            f"{e['start_heading_deg']}°",
            e["status"].replace("_", " "),
            str(r.rows),
            str(r.cruise_s),
            "-" if not w else f"{w['median_mps']:.1f} / {w['max_mps']:.1f}",
            "-" if over is None else f"{over:.0f}",
            str(s["phases_s"].get("landing", 0)),
            ", ".join(f"{t:.2f}" for t in s["touchdown_mps"]) or "none",
            f"{r.max_altitude_m:.0f}",
            f"{s['battery_pct']['start'] - s['battery_pct']['end']:.0f}",
            str(r.battery_checks) if loaded else "-",
            _alerts(r.rule_alerts, loaded),
            _alerts(r.ml_alerts, loaded),
            "; ".join(s["warnings"]) or "none",
        ]) + " |")
    lines += ["", "Notes from `sitl/flights.json`:", ""]
    lines += [f"- `{Path(r.entry['file']).name}`: {r.entry['note']}" for r in results if r.entry.get("note")]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    for noisy in ("httpx", "ingestion", "repository", "sitl_etl", "load_reference", "send_telemetry"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    ap = argparse.ArgumentParser(description="Rebuild the SITL database and results from sitl/flights.json")
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--db", type=Path, default=Path("data/sitl.db"))
    ap.add_argument("--out", type=Path, default=Path("data/sitl"))
    ap.add_argument("--results", type=Path, default=SITL_DIR / "RESULTS.md")
    args = ap.parse_args(argv)
    results = rebuild(args.manifest, args.db, args.out)
    args.results.write_text(results_markdown(results), encoding="utf-8")
    flown = [r for r in results if r.battery_checks is not None]
    log.info("%d flights (%d loaded into %s); rule alerts %d, ML alerts %d -> %s", len(results), len(flown),
             args.db, sum(sum(r.rule_alerts.values()) for r in flown),
             sum(sum(r.ml_alerts.values()) for r in flown), args.results)
    return 0


if __name__ == "__main__":
    sys.exit(main())
